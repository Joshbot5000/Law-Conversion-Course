const { chromium } = require('playwright');
const path = require('path');
const T = __dirname;
const ok = (c, m) => { console.log((c ? 'ok: ' : 'FAIL: ') + m); if (!c) process.exitCode = 1; };
(async () => {
  const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1280, height: 860 } });
  await ctx.addInitScript({ path: path.join(T, 'sample_seed.js') });
  await ctx.addInitScript({ path: path.join(T, 'mockclaude.js') });
  const page = await ctx.newPage(); const errs = []; page.on('pageerror', e => errs.push(e.message));
  await page.goto('file://' + path.join(T, 'online_wrapped.html'));
  await page.evaluate(() => { localStorage.clear(); sessionStorage.clear(); window.name = ''; localStorage.setItem('lawRevisionApp.migrated', '1'); }); await page.reload();
  await page.waitForFunction(() => document.querySelector('#statTotal').textContent !== '0'); await page.waitForTimeout(300);
  const onTop = sel => page.evaluate(s => { const el = document.querySelector(s + ' .modal-box'); const r = el.getBoundingClientRect(); const hit = document.elementFromPoint(r.left + r.width / 2, r.top + 30); return el.contains(hit); }, sel);
  await page.click('#reviewBtn'); await page.waitForSelector('#rvShow');
  await page.keyboard.press('e'); await page.waitForTimeout(300);
  ok(await onTop('#entryModal'), 'edit form opens above review');
  await page.fill('#fStrategy', 'Edited during review'); await page.click('#saveEntryBtn'); await page.waitForTimeout(300);
  ok((await page.textContent('#reviewBody')).length > 0 && await page.isVisible('#reviewModal'), 'back in review after saving');
  await page.keyboard.press('a'); await page.waitForTimeout(300);
  ok(await onTop('#askModal'), 'ask opens above review');
  await page.keyboard.press('Escape'); await page.keyboard.press('Escape');
  await page.fill('#searchInput', 'Bonnington'); await page.waitForTimeout(300);
  await page.click('.card [data-action=ask]'); await page.click('[data-preset="1"]'); await page.waitForSelector('.cite-list');
  await page.click('.cite-list button[data-cite="C1"]'); await page.waitForTimeout(200);
  ok(await onTop('#peekModal'), 'card peek above ask');
  await page.click('#peekBody [data-action=edit]'); await page.waitForTimeout(200);
  ok(await onTop('#entryModal'), 'edit above peek');
  await page.fill('#fName', 'Donoghue v Stevenson'); await page.selectOption('#fModule', 'tort');
  await page.click('#saveEntryBtn'); await page.waitForTimeout(200);
  ok(await onTop('#dialogModal') || !(await page.isVisible('#dialogModal')), 'duplicate warning above edit (if shown)');
  ok(errs.length === 0, 'no errors ' + JSON.stringify(errs));
  await b.close();
})();
